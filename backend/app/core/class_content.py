def normalize_grade(grade: Any) -> str:
    """Normalizes any grade input like '10th', 'कक्षा 10', 10, 'Class 5' to simple numeric string '5'-'10'.
    Raises ValueError if grade is not between 5 and 10."""
    if not grade:
        return "10"
    s = str(grade).strip()
    match = re.search(r"\b(10|5|6|7|8|9)\b", s)
    if match:
        return match.group(1)
    digits = re.findall(r"\d+", s)
    if digits and digits[0] in CLASS_WISE_CONTENT:
        return digits[0]
    raise ValueError("इस कक्षा और चयनित अध्यायों के लिए पर्याप्त प्रश्न उपलब्ध नहीं हैं। कृपया सही पाठ्यपुस्तक या अधिक अध्याय चुनें।")


def get_class_content(grade: Any) -> Dict[str, Any]:
    """
    Returns authentic curriculum data for the specified class.
    Raises strict Hindi error if grade is not found.
    """
    g_key = normalize_grade(grade)
    if g_key not in CLASS_WISE_CONTENT:
        raise ValueError("इस कक्षा और चयनित अध्यायों के लिए पर्याप्त प्रश्न उपलब्ध नहीं हैं। कृपया सही पाठ्यपुस्तक या अधिक अध्याय चुनें।")
    return CLASS_WISE_CONTENT[g_key]


def get_prose_for_class(grade: Any, selected_chapters: Optional[List[str]] = None) -> List[Dict[str, Any]]:
    """Retrieves prose passages for a grade, optionally filtered by selected chapters."""
    content = get_class_content(grade)
    all_prose = content.get("prose_passages", [])
    if not selected_chapters:
        return all_prose
    
    sel_norm = [c.strip().lower() for c in selected_chapters if c]
    matched = []
    for p in all_prose:
        ch = p.get("chapter", "").strip().lower()
        if any(s in ch or ch in s for s in sel_norm):
            matched.append(p)
    return matched if matched else all_prose


